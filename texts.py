FA_MAP = str.maketrans("0123456789,.", "۰۱۲۳۴۵۶۷۸۹٬٫")


def fa(x) -> str:
    """تبدیل عدد یا رشته به رقم‌های فارسی تمیز: 993599 → ۹۹۳٬۵۹۹"""
    if x is None:
        return "۰"
    s = f"{x:,}" if isinstance(x, int) else str(x)
    return s.translate(FA_MAP)


def money(cid: str = "us", amount: int = 0) -> str:
    """نمایش مبلغ با واحد دلار."""
    return f"{fa(int(amount or 0))} دلار"


def esc(s) -> str:
    return html.escape(str("" if s is None else s))


def hdr(title: str, emoji: str = "⚔️") -> str:
    """سربرگ استاندارد بازی با خط‌کشی."""
    return f"{emoji} <b>{esc(title)}</b>\n{FULL}"


def row(label: str, value) -> str:
    """سطر مشخصات: برچسب — مقدار."""
    return f"▫️ {label}: <b>{esc(fa(value))}</b>"


def mention(uid: int, name: str) -> str:
    """تگ امن تلگرام با لینک مستقیم به کاربر."""
    clean_name = esc(name or "فرمانده")
    return f'<a href="tg://user?id={uid}">{clean_name}</a>'


