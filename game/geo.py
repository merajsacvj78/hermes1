def is_neighbor(a: str, b: str) -> bool:
    """آیا دو کشور مرز زمینی مستقیم دارند؟"""
    return b in NEIGHBORS.get(a, set())


def coastal(cid: str) -> bool:
    """آیا کشور به دریا دسترسی دارد؟"""
    return cid in COASTAL


def get_cities(cid: str) -> list:
    """فهرست شهرهای یک کشور."""
    return CITIES.get(cid, ["پایتخت", "شهر مرکزی", "بندر اصلی"])


def occupied(cid: str) -> list:
    """شهرهای اشغال‌شده‌ی یک کشور."""
    return db.jload(db.kv_get(f"occupied:{cid}"), []) or []


def occupy_city(cid: str, city: str, by: str):
    """اشغال یک شهر توسط کشور متخاصم."""
    occ = occupied(cid)
    if city not in occ:
        occ.append(city)
        db.kv_set(f"occupied:{cid}", json.dumps(occ, ensure_ascii=False))


def liberate_city(cid: str, city: str):
    """آزادسازی یک شهر."""
    occ = occupied(cid)
    if city in occ:
        occ.remove(city)
        db.kv_set(f"occupied:{cid}", json.dumps(occ, ensure_ascii=False))


def colony_of(cid: str) -> str | None:
    """کشوری که این کشور مستعمره‌اش شده است."""
    return db.kv_get(f"colony_of:{cid}")


def set_colony(cid: str, overlord_cid: str):
    """تبدیل به مستعمره."""
    db.kv_set(f"colony_of:{cid}", overlord_cid)


def free_colony(cid: str):
    """آزادسازی از وضعیت مستعمره."""
    db.kv_del(f"colony_of:{cid}")
    db.kv_set(f"occupied:{cid}", "[]")


