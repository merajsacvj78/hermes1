def build_base(uid: int, city: str, base_type: str) -> str:
    """ساخت پایگاه نظامی در یکی از شهرهای کشور."""
    from game import state
    p = state.active(uid)
    if not p:
        return "⚠️ ابتدا با دستور «شروع» کشورتان را انتخاب کنید."

    cid = p["country"]
    cities = get_cities(cid)
    if city not in cities:
        return f"⚠️ شهر <b>{city}</b> در قلمرو کشور شما قرار ندارد."

    b_info = BASE_TYPES.get(base_type)
    if not b_info:
        return "⚠️ نوع پایگاه نامعتبر است."

    existing = db.one("SELECT * FROM bases WHERE cid=? AND city=? AND base_type=?", (cid, city, base_type))
    if existing:
        return f"⚠️ شما قبلاً <b>{b_info['name']}</b> در شهر <b>{city}</b> ساخته‌اید."

    cost = b_info["cost"]
    if p["money"] < cost:
        return f"⚠️ موجودی ناکافی! ساخت این پایگاه به {texts.money(cid, cost)} نیاز دارد (موجودی: {texts.money(cid, p['money'])})."

    db.ex("UPDATE users SET money=money-? WHERE uid=?", (cost, uid))
    db.ex("""
    INSERT INTO bases(cid, city, base_type, level, hp, created)
    VALUES(?, ?, ?, 1, ?, ?)
    """, (cid, city, base_type, b_info["hp"], db.now()))

    return f"""🏗️ <b>احداث پایگاه نظامی موفقیت‌آمیز بود!</b>
{texts.FULL}
📍 موقعیت: <b>{city}</b>
🏛️ عنوان: <b>{b_info['name']}</b>
🛡️ استحکامات: <b>{b_info['hp']} HP</b>
⚡ مزیت استراتژیک: {b_info['bonus']}
💵 هزینه: {texts.money(cid, cost)}"""


